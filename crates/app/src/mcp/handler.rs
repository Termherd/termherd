//! The MCP tool surface exposed to hosted Claude sessions.
//!
//! [`TermherdMcp`] is an rmcp [`ServerHandler`]: it answers `tools/list` and
//! `tools/call` for the live-bridge tools. Each tool is a thin adapter — it
//! translates the call into a [`Request`] on the async-transport bridge, awaits
//! the timeout-bounded [`Reply`], and shapes it back into an MCP result. No state
//! and no `core` access live here; the shell owns `core::App` and answers on the
//! bridge, so a tool can never touch it directly.

use std::time::Duration;

use rmcp::{
    ErrorData, ServerHandler,
    handler::server::{router::tool::ToolRouter, wrapper::Parameters},
    model::{
        CallToolResult, ContentBlock, Implementation, ProtocolVersion, ServerCapabilities,
        ServerInfo,
    },
    schemars::JsonSchema,
    tool, tool_handler, tool_router,
};
use serde::{Deserialize, Serialize};
use termherd_core::keymap::ChordError;
use termherd_core::snapshot::DEFAULT_TEXT_LINES;
use termherd_core::workspace::SplitDir;
use termherd_core::{
    Action as KeymapAction, KeyChord, Section, SessionStatus, SnapshotFilter, TerminalScope,
};

use crate::shell::bridge::{
    Action, BridgeHandle, CallError, Press, PressStep, Reply, Request, SessionInfo, SessionKind,
};
use crate::snapshot_dto::{SnapshotDto, status_str};

/// How long a tool waits for the shell to answer before failing the caller.
/// Bounds the whole round-trip (enqueue + reply) via [`BridgeHandle::call`], so
/// a wedged shell surfaces as a tool error, never a hang (Q7).
const CALL_TIMEOUT: Duration = Duration::from_secs(5);

/// Default bound for `wait_for_status` when the caller names none. Long enough
/// for a real command, short enough that a forgotten wait reports back.
const DEFAULT_WAIT_MS: u64 = 30_000;

/// Hard cap on a wait, whatever the caller asks for — the outer Q7 guarantee
/// that no bridge call can park a caller indefinitely.
const MAX_WAIT_MS: u64 = 300_000;

/// Bound on a `screenshot` round-trip. Longer than [`CALL_TIMEOUT`]: it covers
/// an async window frame *plus* a multi-megapixel resample and PNG encode,
/// legitimately slower than a state read — but still bounded (Q7).
const SCREENSHOT_TIMEOUT: Duration = Duration::from_secs(15);

/// Default bound on a screenshot's width. Sized for a model's context, not for
/// a display: an unscaled retina window is megabytes of base64.
const DEFAULT_MAX_WIDTH: u32 = 1200;

/// Range a caller's `max_width` is clamped into. The floor keeps an image
/// legible; the ceiling keeps one tool call from swamping the context it is
/// supposed to inform.
const MIN_MAX_WIDTH: u32 = 64;
const MAX_MAX_WIDTH: u32 = 4096;

/// Bound on the status read-back after a wait timed out. Deliberately short: it
/// is a courtesy on top of an answer the caller has already earned, so it must
/// barely extend the wait it follows.
const READ_BACK_TIMEOUT: Duration = Duration::from_millis(250);

/// The live-bridge MCP server handler. Holds only the bridge into the shell —
/// cloned fresh per session by the transport's service factory.
#[derive(Clone)]
pub struct TermherdMcp {
    bridge: BridgeHandle,
    tool_router: ToolRouter<Self>,
}

#[tool_router(router = tool_router)]
impl TermherdMcp {
    /// Build a handler over `bridge`. The tool router is generated by the
    /// `#[tool_router]` macro from the `#[tool]` methods below.
    pub fn new(bridge: BridgeHandle) -> Self {
        Self {
            bridge,
            tool_router: Self::tool_router(),
        }
    }

    /// The spike tool: list the live terminal sessions termherd is hosting, each
    /// with its stable handle, so an MCP client can address them.
    #[tool(
        name = "list_sessions",
        description = "List the live terminal sessions termherd is hosting. Each \
                       row carries a stable `handle` (address it in later calls), \
                       the tab title, working directory, kind (shell or claude), \
                       the resumed Claude id if any, and current activity status."
    )]
    async fn list_sessions(&self) -> Result<CallToolResult, ErrorData> {
        let reply = self
            .bridge
            .call(Request::ListSessions, CALL_TIMEOUT)
            .await
            .map_err(|error| ErrorData::internal_error(error.to_string(), None))?;
        let Reply::Sessions(sessions) = reply else {
            return Err(ErrorData::internal_error(
                "bridge answered the wrong reply kind",
                None,
            ));
        };
        let rows: Vec<SessionDto> = sessions.iter().map(SessionDto::from).collect();
        let value = serde_json::to_value(&rows)
            .map_err(|error| ErrorData::internal_error(error.to_string(), None))?;
        Ok(CallToolResult::structured(value))
    }

    /// A filterable, read-only snapshot of the whole workspace — the structured
    /// "DOM" a client reads to perceive termherd before acting. Light by default
    /// (structure only, no terminal text); scope terminal text to named handles.
    #[tool(
        name = "snapshot",
        description = "A filterable snapshot of termherd's whole state: config, \
                       the session-browser sidebar, and the open tabs with their \
                       panes (each pane's stable handle, kind, cwd, status). Light \
                       by default — no terminal text. Args (all optional): \
                       `sections` (any of \"config\", \"sidebar\", \"tabs\"; omit \
                       for all), `terminals` (session handles to include screen \
                       text for; omit for none — read the structure first, then \
                       request a handle), `text_lines` (trailing lines per \
                       requested terminal, default 40)."
    )]
    async fn snapshot(
        &self,
        Parameters(args): Parameters<SnapshotArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let reply = self
            .bridge
            .call(Request::Snapshot(args.into_filter()), CALL_TIMEOUT)
            .await
            .map_err(|error| ErrorData::internal_error(error.to_string(), None))?;
        let Reply::Snapshot(snapshot) = reply else {
            return Err(ErrorData::internal_error(
                "bridge answered the wrong reply kind",
                None,
            ));
        };
        let value = serde_json::to_value(SnapshotDto::from(&snapshot))
            .map_err(|error| ErrorData::internal_error(error.to_string(), None))?;
        Ok(CallToolResult::structured(value))
    }

    /// Open a new terminal session and focus it. → `open_session`.
    #[tool(
        name = "open_session",
        description = "Open a new terminal session and focus it. Args: `project` \
                       (working directory; omit for the home dir), `kind` \
                       (\"shell\" or \"claude\", default \"shell\"). Returns the \
                       new session's `focused_handle`."
    )]
    async fn open_session(
        &self,
        Parameters(args): Parameters<OpenArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let action = Action::Open {
            project: args.project,
            kind: match args.kind.as_deref() {
                None | Some("shell") => SessionKind::Shell,
                Some("claude") => SessionKind::Claude,
                Some(other) => {
                    return Err(ErrorData::invalid_params(
                        format!("unknown kind {other:?}; expected \"shell\" or \"claude\""),
                        None,
                    ));
                }
            },
        };
        self.act(action).await
    }

    /// Split a pane, opening a fresh session beside it. → `split_pane`.
    #[tool(
        name = "split_pane",
        description = "Split a pane, opening a fresh shell beside it and focusing \
                       it. Args: `direction` (\"vertical\" = side by side, \
                       \"horizontal\" = stacked; default \"vertical\"), `pane` \
                       (session handle to split; omit for the focused pane). \
                       Returns the new pane's `focused_handle`."
    )]
    async fn split_pane(
        &self,
        Parameters(args): Parameters<SplitArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let dir = match args.direction.as_deref() {
            None | Some("vertical") | Some("v") => SplitDir::Vertical,
            Some("horizontal") | Some("h") => SplitDir::Horizontal,
            Some(other) => {
                return Err(ErrorData::invalid_params(
                    format!("unknown direction {other:?}; expected \"vertical\" or \"horizontal\""),
                    None,
                ));
            }
        };
        let pane = parse_optional_handle(args.pane)?;
        self.act(Action::Split { pane, dir }).await
    }

    /// Move focus to the pane hosting a session. → `focus_pane`.
    #[tool(
        name = "focus_pane",
        description = "Move focus to the pane hosting a session, and hand it the \
                       keyboard. Args: `session` (its stable handle). Returns the \
                       resulting `focused_handle`."
    )]
    async fn focus_pane(
        &self,
        Parameters(args): Parameters<FocusArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let session = parse_handle(&args.session)?;
        self.act(Action::Focus { session }).await
    }

    /// Give a tab a manual name. → `rename_tab`.
    #[tool(
        name = "rename_tab",
        description = "Give the tab at `tab` (0-based index, as `snapshot` reports \
                       tab order) a manual name. A blank `title` reverts to the \
                       derived title. Returns the current `focused_handle`."
    )]
    async fn rename_tab(
        &self,
        Parameters(args): Parameters<RenameArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        self.act(Action::Rename {
            tab: args.tab,
            title: args.title,
        })
        .await
    }

    /// Close a pane; a lone pane closes its whole tab. → `close_pane`.
    #[tool(
        name = "close_pane",
        description = "Close a pane and kill its terminal. Args: `pane` (session \
                       handle to close; omit for the focused pane). A lone pane is \
                       its whole tab, which closes. Returns the resulting \
                       `focused_handle` (null when the workspace is now empty)."
    )]
    async fn close_pane(
        &self,
        Parameters(args): Parameters<CloseArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let pane = parse_optional_handle(args.pane)?;
        self.act(Action::Close { pane }).await
    }

    /// Type text into a session's terminal; the wait is a separate call.
    /// → `run_in_session`.
    #[tool(
        name = "run_in_session",
        description = "Type text into a session's terminal, as if typed at the \
                       keyboard. Returns as soon as the text is sent — it does \
                       not wait for the command to finish. To act on the result, \
                       follow with `wait_for_status` then `read_terminal`; do \
                       not poll `snapshot`, which races the transition you are \
                       watching for. Include a trailing newline in `text` to \
                       submit a command. Args: `session` (its stable handle), \
                       `text`. Returns the `focused_handle`."
    )]
    async fn run_in_session(
        &self,
        Parameters(args): Parameters<RunArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let session = parse_handle(&args.session)?;
        self.act(Action::Run {
            session,
            bytes: args.text.into_bytes(),
        })
        .await
    }

    /// Block until a session's activity reaches one of the given statuses — the
    /// synchronisation half of `act → wait → observe`.
    #[tool(
        name = "wait_for_status",
        description = "Wait until a session's activity reaches one of `statuses` \
                       (default: idle or attention), then report it. Pair it \
                       with `run_in_session`, which returns immediately: run, \
                       wait, then `read_terminal`. Args: `session` (handle), \
                       `statuses` (any of \"starting\", \"busy\", \"idle\", \
                       \"attention\", \"exited\"), `timeout_ms` (default 30000, \
                       capped at 300000). A session that exits settles the wait \
                       whatever you asked for — it can no longer reach it. \
                       Returns `{ status, timed_out }`: on timeout the status is \
                       the session's current one, not an error."
    )]
    async fn wait_for_status(
        &self,
        Parameters(args): Parameters<WaitArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let session = parse_handle(&args.session)?;
        let targets = parse_statuses(args.statuses)?;
        let timeout = wait_timeout(args.timeout_ms);

        match self
            .bridge
            .call(Request::WaitForStatus { session, targets }, timeout)
            .await
        {
            Ok(Reply::Waited(outcome)) => {
                if let Some(reason) = outcome.error {
                    return Err(ErrorData::invalid_params(reason, None));
                }
                Ok(CallToolResult::structured(serde_json::json!({
                    "status": outcome.status.map(status_str),
                    "timed_out": false,
                })))
            }
            Ok(_) => Err(ErrorData::internal_error(
                "bridge answered the wrong reply kind",
                None,
            )),
            // The wait outlived its bound. Report *where the session got to*
            // rather than a bare failure: an agent that waited 30s needs the
            // current status to decide whether to keep waiting or give up.
            Err(CallError::Timeout(_)) => {
                let status = self.current_status(session).await;
                Ok(CallToolResult::structured(serde_json::json!({
                    "status": status,
                    "timed_out": true,
                })))
            }
            Err(error) => Err(ErrorData::internal_error(error.to_string(), None)),
        }
    }

    /// The visible text of one session's terminal — the deep read `snapshot`
    /// deliberately leaves out.
    #[tool(
        name = "read_terminal",
        description = "Read the visible text of one session's terminal. Args: \
                       `session` (handle), `lines` (trailing lines to keep, \
                       default 40). Returns `{ text, rendered }`; `rendered` is \
                       false when the session is live but its screen has not \
                       been drawn yet — retry rather than giving up on the \
                       handle."
    )]
    async fn read_terminal(
        &self,
        Parameters(args): Parameters<ReadArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let session = parse_handle(&args.session)?;
        let lines = args.lines.unwrap_or(DEFAULT_TEXT_LINES);
        let reply = self
            .bridge
            .call(Request::ReadTerminal { session, lines }, CALL_TIMEOUT)
            .await
            .map_err(|error| ErrorData::internal_error(error.to_string(), None))?;
        let Reply::Terminal(read) = reply else {
            return Err(ErrorData::internal_error(
                "bridge answered the wrong reply kind",
                None,
            ));
        };
        if let Some(reason) = read.error {
            return Err(ErrorData::invalid_params(reason, None));
        }
        Ok(CallToolResult::structured(serde_json::json!({
            "text": read.text.as_deref().unwrap_or_default(),
            "rendered": read.text.is_some(),
        })))
    }

    /// The window's pixels — what the text `snapshot` cannot show.
    #[tool(
        name = "screenshot",
        description = "Capture termherd's window as a PNG image — the pixel \
                       companion to the text `snapshot`, for render, colour and \
                       glyph questions text cannot answer. Args: `max_width` \
                       (bound on the returned width, default 1200, 64–4096); \
                       the frame is area-averaged down to fit, never upscaled, \
                       and a total-pixel ceiling bounds tall windows the width \
                       alone would not. The reported `width`/`height` are what \
                       you actually received. A default-bound window costs on \
                       the order of 200 kB of PNG, a third more again as \
                       base64 — lower `max_width` when a coarse view will do. \
                       Prefer \
                       `snapshot` / `read_terminal` for anything textual — they \
                       cost a fraction of the context an image does."
    )]
    async fn screenshot(
        &self,
        Parameters(args): Parameters<ScreenshotArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let max_width = args
            .max_width
            .unwrap_or(DEFAULT_MAX_WIDTH)
            .clamp(MIN_MAX_WIDTH, MAX_MAX_WIDTH);
        let reply = self
            .bridge
            .call(Request::Screenshot { max_width }, SCREENSHOT_TIMEOUT)
            .await
            .map_err(|error| ErrorData::internal_error(error.to_string(), None))?;
        let Reply::Shot(shot) = reply else {
            return Err(ErrorData::internal_error(
                "bridge answered the wrong reply kind",
                None,
            ));
        };
        let Some(png) = shot.png else {
            return Ok(no_pixels(shot.error));
        };
        let data = base64::Engine::encode(&base64::engine::general_purpose::STANDARD, &png);
        let mut result = CallToolResult::success(vec![ContentBlock::image(data, "image/png")]);
        // The size the caller *received*, which is not the size it asked for
        // when the window was smaller than the bound.
        result.structured_content = Some(serde_json::json!({
            "width": shot.width,
            "height": shot.height,
        }));
        Ok(result)
    }

    /// Press key chords at termherd's own interface — the binding half of the
    /// keyboard surface.
    #[tool(
        name = "press_keys",
        description = "Press key chords at termherd's own interface (not at a \
                       terminal — typing into a session is `run_in_session`). \
                       Chords use the same syntax as the `keys` section of \
                       settings.json — \"cmd+shift+s\", \"ctrl+tab\", \
                       \"escape\" — and resolve through the *live* keymap, so \
                       this exercises whatever the user rebound. Args: `keys` \
                       (chords, applied in order). Returns one `steps` entry per \
                       chord — `ran` (with the action's name), `inert` (the \
                       action exists but has no surface yet, so nothing \
                       happened; do not retry), `overlay` (an open prompt \
                       consumed it; \"escape\" usually cancels and \"enter\" \
                       confirms — but on `quit-confirm` \"enter\" quits the app, \
                       killing every session and this connection, and \
                       `session-rename` answers to neither, so only a human can \
                       clear that one), \
                       `typed` (bound to nothing, so it reached the focused \
                       terminal), `unbound` (nothing claimed it) — plus the \
                       resulting `focused_handle`. Use `run_action` instead \
                       when you want the behaviour regardless of bindings."
    )]
    async fn press_keys(
        &self,
        Parameters(args): Parameters<PressKeysArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let presses = args
            .keys
            .iter()
            .map(|spec| {
                KeyChord::parse(spec)
                    .map(Press::Chord)
                    .map_err(|error| invalid_chord(spec, &error))
            })
            .collect::<Result<Vec<_>, _>>()?;
        self.press(presses, &args.keys).await
    }

    /// Run keymap actions by name — the behaviour half, stable across rebinds.
    #[tool(
        name = "run_action",
        description = "Run termherd's keymap actions by name, skipping the \
                       keymap — so it keeps working whatever the user rebound, \
                       where `press_keys` tests the binding itself. Names are \
                       the kebab-case ones the `keys` section of settings.json \
                       speaks: \"split-vertical\", \"next-tab\", \
                       \"toggle-sidebar\", \"capture\", \"activate-tab-3\". An \
                       unknown name is rejected and the error shows the syntax; \
                       this server serves tools only, so there is no resource to \
                       enumerate them from. Args: `actions` (applied in order). An open prompt still \
                       consumes an action, exactly as it consumes a keypress, \
                       and the step reports which one — answer it with \
                       `press_keys([\"enter\"])`. Returns `steps` plus the \
                       resulting `focused_handle`."
    )]
    async fn run_action(
        &self,
        Parameters(args): Parameters<RunActionArgs>,
    ) -> Result<CallToolResult, ErrorData> {
        let presses = args
            .actions
            .iter()
            .map(|name| {
                KeymapAction::from_config_name(name)
                    .map(Press::Command)
                    .ok_or_else(|| unknown_action(name))
            })
            .collect::<Result<Vec<_>, _>>()?;
        self.press(presses, &args.actions).await
    }
}

impl TermherdMcp {
    /// A session's current activity, read back after a wait timed out. Best
    /// effort by design: `None` covers a handle that no longer resolves *and* a
    /// read-back that failed. The likeliest cause of the original timeout is a
    /// wedged shell, which would fail this call too — and turning that into an
    /// error would swallow the `timed_out` answer the caller is owed.
    async fn current_status(&self, session: u64) -> Option<&'static str> {
        match self
            .bridge
            .call(Request::ListSessions, READ_BACK_TIMEOUT)
            .await
        {
            Ok(Reply::Sessions(sessions)) => sessions
                .iter()
                .find(|info| info.handle == session.to_string())
                .map(|info| status_str(info.status)),
            Ok(_) => None,
            Err(error) => {
                tracing::debug!(%error, "could not read the status back after a wait timeout");
                None
            }
        }
    }

    /// Send a press sequence over the bridge and shape its [`PressOutcome`] into
    /// a tool result. `requested` is what the caller asked for, echoed back into
    /// each step positionally: a caller reading "the third one hit an overlay"
    /// should not have to count its own arguments to learn which chord that was.
    async fn press(
        &self,
        presses: Vec<Press>,
        requested: &[String],
    ) -> Result<CallToolResult, ErrorData> {
        let reply = self
            .bridge
            .call(Request::Press(presses), CALL_TIMEOUT)
            .await
            .map_err(|error| ErrorData::internal_error(error.to_string(), None))?;
        let Reply::Pressed(outcome) = reply else {
            return Err(ErrorData::internal_error(
                "bridge answered the wrong reply kind",
                None,
            ));
        };
        if let Some(reason) = outcome.error {
            return Err(ErrorData::internal_error(reason, None));
        }
        // The echo is positional, so a step count that does not match the press
        // count would silently truncate — or worse, misalign — into a report
        // indistinguishable from a correct one. The shell answers one step per
        // press, so this is a loud failure rather than a quiet wrong answer.
        if outcome.steps.len() != requested.len() {
            return Err(ErrorData::internal_error(
                format!(
                    "the shell answered {} steps for {} presses",
                    outcome.steps.len(),
                    requested.len()
                ),
                None,
            ));
        }
        let steps: Vec<PressStepDto> = outcome
            .steps
            .iter()
            .zip(requested)
            .map(|(step, press)| PressStepDto::new(press, step))
            .collect();
        let value = serde_json::json!({
            "steps": steps,
            "focused_handle": outcome.focused,
        });
        Ok(CallToolResult::structured(value))
    }

    /// Send an [`Action`] over the bridge and shape its [`ActionOutcome`] into a
    /// tool result: a rejection (unknown handle / out-of-range tab) becomes an
    /// `invalid_params` error, an applied action a `{ focused_handle }` object.
    async fn act(&self, action: Action) -> Result<CallToolResult, ErrorData> {
        let reply = self
            .bridge
            .call(Request::Act(action), CALL_TIMEOUT)
            .await
            .map_err(|error| ErrorData::internal_error(error.to_string(), None))?;
        let Reply::Acted(outcome) = reply else {
            return Err(ErrorData::internal_error(
                "bridge answered the wrong reply kind",
                None,
            ));
        };
        if let Some(reason) = outcome.error {
            return Err(ErrorData::invalid_params(reason, None));
        }
        let value = serde_json::json!({ "focused_handle": outcome.focused });
        Ok(CallToolResult::structured(value))
    }
}

#[tool_handler(router = self.tool_router)]
impl ServerHandler for TermherdMcp {
    fn get_info(&self) -> ServerInfo {
        // rmcp's `ServerInfo`/`Implementation` are `#[non_exhaustive]`, so build
        // from a default and set the fields we care about rather than a literal.
        let mut server = Implementation::from_build_env();
        server.name = "termherd".into();
        server.version = env!("CARGO_PKG_VERSION").into();

        let mut info = ServerInfo::default();
        info.protocol_version = ProtocolVersion::LATEST;
        info.capabilities = ServerCapabilities::builder().enable_tools().build();
        info.server_info = server;
        info.instructions = Some(
            "termherd's live bridge: read and (later) drive the terminal \
             sessions it is hosting."
                .into(),
        );
        info
    }
}

/// The on-the-wire shape of a session for the `list_sessions` tool: the stable
/// external handle plus flat, string-typed fields an MCP client can read without
/// knowing termherd's internal enums.
#[derive(Serialize)]
struct SessionDto {
    /// Stable external handle (the runtime session id).
    handle: String,
    title: String,
    cwd: Option<String>,
    /// `"shell"` or `"claude"`.
    kind: &'static str,
    /// The resumed Claude session id, if any (the *unstable* id — never the
    /// handle).
    resume_id: Option<String>,
    /// `"starting"`, `"busy"`, `"idle"`, `"attention"`, or `"exited"`.
    status: &'static str,
}

impl From<&SessionInfo> for SessionDto {
    fn from(info: &SessionInfo) -> Self {
        Self {
            handle: info.handle.clone(),
            title: info.title.clone(),
            cwd: info.cwd.clone(),
            kind: match info.kind {
                SessionKind::Shell => "shell",
                SessionKind::Claude => "claude",
            },
            resume_id: info.resume_id.clone(),
            status: status_str(info.status),
        }
    }
}

/// The `snapshot` tool's arguments — every field optional so a bare call is the
/// light default. Deserialised from the MCP `arguments` object.
#[derive(Debug, Default, Deserialize, JsonSchema)]
#[schemars(crate = "rmcp::schemars")]
struct SnapshotArgs {
    /// Sections to include: any of `"config"`, `"sidebar"`, `"tabs"`. Omit for
    /// all three. Unknown names are ignored.
    #[serde(default)]
    sections: Option<Vec<String>>,
    /// Session handles (as strings, as `list_sessions` reports them) to include
    /// terminal text for. Omit (or empty) for none.
    #[serde(default)]
    terminals: Option<Vec<String>>,
    /// Include the focused pane's terminal text — a one-call shortcut when you
    /// don't yet know its handle. Ignored when `terminals` names handles.
    #[serde(default)]
    focused_terminal: Option<bool>,
    /// Trailing terminal lines to keep per requested session.
    #[serde(default)]
    text_lines: Option<usize>,
}

impl SnapshotArgs {
    /// Map the flat MCP arguments onto the core [`SnapshotFilter`]. Omitted
    /// fields fall back to the light default. Explicit handles win over the
    /// `focused_terminal` shortcut.
    fn into_filter(self) -> SnapshotFilter {
        let default = SnapshotFilter::default();
        let sections = match self.sections {
            Some(names) => names
                .iter()
                .filter_map(|name| match name.as_str() {
                    "config" => Some(Section::Config),
                    "sidebar" => Some(Section::Sidebar),
                    "tabs" => Some(Section::Tabs),
                    _ => None,
                })
                .collect(),
            None => default.sections,
        };
        let terminals = match self.terminals {
            Some(handles) if !handles.is_empty() => {
                TerminalScope::Only(handles.iter().filter_map(|h| h.parse().ok()).collect())
            }
            _ if self.focused_terminal == Some(true) => TerminalScope::Focused,
            _ => TerminalScope::None,
        };
        SnapshotFilter {
            sections,
            terminals,
            text_lines: self.text_lines.unwrap_or(default.text_lines),
        }
    }
}

